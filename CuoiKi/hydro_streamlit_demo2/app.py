@st.cache_data(show_spinner=False)
def load_history(cfg: DamConfig) -> pd.DataFrame:
    if not cfg.data_csv.exists():
        raise FileNotFoundError(f"Missing data CSV: {cfg.data_csv}")

    df = pd.read_csv(cfg.data_csv)

    if cfg.time_col not in df.columns:
        raise ValueError(f"CSV must contain time column '{cfg.time_col}'")

    df[cfg.time_col] = pd.to_datetime(df[cfg.time_col], errors="coerce")
    df = df.dropna(subset=[cfg.time_col]).sort_values(cfg.time_col)
    df = df.set_index(cfg.time_col)

    # Ensure numeric columns are numeric when possible
    for c in df.columns:
        if c == cfg.time_col:
            continue
        if df[c].dtype == object:
            df[c] = pd.to_numeric(df[c], errors="ignore")

    return df


@st.cache_resource(show_spinner=False)
def load_model(cfg: DamConfig):
    if not cfg.model_pkl.exists():
        raise FileNotFoundError(f"Missing model file: {cfg.model_pkl}")
    return joblib.load(cfg.model_pkl)


@st.cache_data(show_spinner=False)
def load_feats(cfg: DamConfig) -> List[str]:
    if not cfg.feats_json.exists():
        raise FileNotFoundError(f"Missing feats json: {cfg.feats_json}")
    feats = json.loads(cfg.feats_json.read_text(encoding="utf-8"))
    if not isinstance(feats, list) or not all(isinstance(x, str) for x in feats):
        raise ValueError("feats json must be a JSON list of strings")
    return feats


