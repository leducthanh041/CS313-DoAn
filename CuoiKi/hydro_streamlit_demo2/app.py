def _parse_feat_requests(train_feats: List[str]) -> Tuple[Dict[str, List[str]], Dict[str, List[int]]]:
    """
    Parse requested rolling stats and lags from train feature names.

    Expected patterns:
      - {col}__mean_24h, {col}__std_3d, {col}__max_28d, {col}__min_7d
      - {col}__lag_24

    Returns:
      roll_map: col -> list of window tokens like ["24h","3d","7d","14d","28d"] (lowercase)
      lag_map:  col -> list of lags (int)
    """
    roll_map: Dict[str, set] = {}
    lag_map: Dict[str, set] = {}

    for f in train_feats:
        if "__" not in f:
            continue
        col, rest = f.split("__", 1)

        if rest.startswith("lag_"):
            try:
                lag = int(rest.replace("lag_", ""))
                lag_map.setdefault(col, set()).add(lag)
            except Exception:
                continue
            continue

        # rolling stats
        for stat in ("mean_", "std_", "max_", "min_"):
            if rest.startswith(stat):
                win = rest.replace(stat, "").strip().lower()
                # normalize e.g. 24h, 3d, 7d, 14d, 28d
                roll_map.setdefault(col, set()).add(win)
                break

    roll_map_out = {k: sorted(list(v), key=lambda x: (int(x[:-1]), x[-1])) for k, v in roll_map.items()}
    lag_map_out = {k: sorted(list(v)) for k, v in lag_map.items()}
    return roll_map_out, lag_map_out


def _to_pandas_window(token: str) -> str:
    """
    Convert '24h' -> '24H', '3d' -> '3D', etc.
    """
    token = token.strip().lower()
    if token.endswith("h"):
        return f"{int(token[:-1])}H"
    if token.endswith("d"):
        return f"{int(token[:-1])}D"
    raise ValueError(f"Unsupported window token: {token}")


def build_row_features_at_T(
    df_history: pd.DataFrame,
    train_feats: List[str],
    T: pd.Timestamp,
    lookback_days_buffer: int = 60,
) -> Tuple[pd.DataFrame, Dict[str, float]]:
    """
    Build a single-row feature dataframe for the selected target time T.

    IMPORTANT (anchor logic):
      - All rolling/lag features are computed at the last available observation time A < T (anchor),
        so that gaps right before T do not break feature construction.
      - Calendar/time features (hour/dow/month/is_weekend) are computed from T (the time you want to predict).

    Returns:
      X_row: shape (1, n_features) aligned to train_feats order
      meta:  diagnostics (anchor_time, gap_hours, etc.)
    """
    meta: Dict[str, float] = {}

    if df_history.empty:
        return pd.DataFrame(columns=train_feats), meta

    # Ensure naive timestamps (demo simplification)
    if df_history.index.tz is not None:
        df_history = df_history.copy()
        df_history.index = df_history.index.tz_convert(None)

    T = pd.Timestamp(T).to_pydatetime()
    T = pd.Timestamp(T)

    # 1) Anchor A = last timestamp strictly before T
    hist_before = df_history[df_history.index < T]
    if hist_before.empty:
        meta["gap_hours"] = float("nan")
        return pd.DataFrame(columns=train_feats), meta

    A = hist_before.index.max()
    meta["anchor_time"] = A.isoformat()
    meta["gap_hours"] = float((T - A).total_seconds() / 3600.0)

    # 2) Work on a buffered history ending at A
    start_time = A - pd.Timedelta(days=lookback_days_buffer)
    df_buf = df_history[(df_history.index >= start_time) & (df_history.index <= A)].copy()
    df_buf = df_buf.sort_index()

    meta["n_rows_in_buffer"] = float(len(df_buf))

    # 3) Which rolling windows and lags are required by the model?
    roll_map, lag_map = _parse_feat_requests(train_feats)

    # 4) Build feature frame on the same index as df_buf
    feat = pd.DataFrame(index=df_buf.index)

    # 4.1 Calendar features from T (target time)
    feat["hour"] = int(T.hour)
    feat["dow"] = int(T.dayofweek)
    feat["month"] = int(T.month)
    feat["is_weekend"] = int(T.dayofweek >= 5)

    # 4.2 Rolling stats at time A (anchor)
    for col, windows in roll_map.items():
        if col not in df_buf.columns:
            continue
        s = pd.to_numeric(df_buf[col], errors="coerce")
        s_shift = s.shift(1)  # exclude current anchor row itself, consistent with training notebooks

        for wtoken in windows:
            w = _to_pandas_window(wtoken)
            r = s_shift.rolling(w, closed="left")

            mean_name = f"{col}__mean_{wtoken}"
            std_name = f"{col}__std_{wtoken}"
            max_name = f"{col}__max_{wtoken}"
            min_name = f"{col}__min_{wtoken}"

            if mean_name in train_feats:
                feat[mean_name] = r.mean()
            if std_name in train_feats:
                feat[std_name] = r.std()
            if max_name in train_feats:
                feat[max_name] = r.max()
            if min_name in train_feats:
                feat[min_name] = r.min()

    # 4.3 Lags at time A (row-based shifts)
    for col, lags in lag_map.items():
        if col not in df_buf.columns:
            continue
        s = pd.to_numeric(df_buf[col], errors="coerce")
        for l in lags:
            name = f"{col}__lag_{l}"
            if name in train_feats:
                feat[name] = s.shift(l)

    # 5) Extract row at anchor A; reindex to train_feats
    if A not in feat.index:
        return pd.DataFrame(columns=train_feats), meta

    X_row = feat.loc[[A]].reindex(columns=train_feats)

    # 6) Diagnostics
    meta["n_missing_feats"] = float(X_row.isna().sum(axis=1).iloc[0])
    return X_row, meta


def safe_predict(
    cfg: DamConfig,
    T: pd.Timestamp,
    lookback_days_buffer: int = 60,
) -> Tuple[Optional[float], pd.DataFrame, Dict[str, float], Optional[str]]:
    """
    Returns: (pred, X_row, meta, error_message)
    """
    df = load_history(cfg)
    model = load_model(cfg)
    feats = load_feats(cfg)

    # Guard: need at least some history covering rolling windows.
    # We do not hardcode 28 days here because different dams have different feature sets.
    X_row, meta = build_row_features_at_T(df, feats, T, lookback_days_buffer=lookback_days_buffer)

    if X_row.empty:
        return None, X_row, meta, "Không có dữ liệu lịch sử trước thời điểm T để tạo feature."

    if X_row.isna().any(axis=1).iloc[0]:
        missing = X_row.columns[X_row.isna().iloc[0]].tolist()
        # Show only first N to avoid huge message
        show_n = 10
        extra = "" if len(missing) <= show_n else f" (và {len(missing) - show_n} feature khác)"
        msg = f"Không thể dự đoán vì thiếu dữ liệu để tạo đủ feature. Thiếu: {missing[:show_n]}{extra}"
        return None, X_row, meta, msg

    try:
        pred = float(np.asarray(model.predict(X_row)).ravel()[0])
        return pred, X_row, meta, None
    except Exception as e:
        return None, X_row, meta, f"Lỗi khi predict: {e}"


